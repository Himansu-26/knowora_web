-- Run this once in Supabase > SQL Editor.
create extension if not exists pg_trgm;
create table if not exists public.identifications (
  id bigint generated by default as identity primary key,
  item_name text not null,
  category text not null,
  confidence integer not null default 0,
  result jsonb not null,
  created_at timestamptz not null default now()
);
create index if not exists identifications_item_name_idx
  on public.identifications using gin (item_name gin_trgm_ops);
-- Backend uses the service-role key, which bypasses RLS. Never put that key in browser code.
alter table public.identifications enable row level security;
-- Do not add public policies. Only the backend service role should access this table.